async function runBabelSmoke(rootURI) {
  const checks = [];
  const cfg = JSON.parse(await babelScope.BabelHost.resource(rootURI + 'test-config.json'));
  const record = async (name, ok) => {
    checks.push({name, ok: !!ok});
    await IOUtils.writeJSON(cfg.report, {running: true, checks});
    if (!ok) throw new Error(name);
  };
  const timeout = setTimeout(async () => {
    await IOUtils.writeJSON(cfg.report, {success: false, error: 'smoke timed out', checks});
    Services.startup.quit(Components.interfaces.nsIAppStartup.eForceQuit);
  }, 240000);
  try {
    await Zotero.Promise.delay(3000);
    const win = Zotero.getMainWindow(), controller = babelScope.BabelDOC;
    await record('plugin and native tools menu loaded', !!win.document.getElementById('babeldoc-local-menu'));
    await record('native item context menu loaded', !!win.document.getElementById('babeldoc-local-context'));
    const config = {...babelScope.BabelCore.defaults, python: cfg.python, model: 'fixture'};
    await controller.save(config, 'fixture-private-key');
    Services.prefs.setStringPref(controller.pref,JSON.stringify({...controller.config(),pages:'99-2'}));
    await record('legacy saved page ranges are ignored',!('pages' in controller.config()));
    await record('password manager stores API key', controller.key(config.baseURL) === 'fixture-private-key');
    await record('API key absent from preferences', !Services.prefs.getStringPref(controller.pref).includes('fixture-private-key'));
    // Import the actual installed BabelDOC package in a native Gecko-launched Python process.
    const ready = await controller.checkEnvironment();
    await record('real BabelDOC 0.6.4 imports through native subprocess', ready.babeldoc === '0.6.4');
    controller.openSettings(win);
    await Zotero.Promise.delay(700);
    let settings = controller.settingsWindow;
    const waitModels = async () => {
      for (let i = 0; i < 800 && (controller.busy || settings.document.getElementById('codexModels').getAttribute('aria-busy') === 'true'); i++) await Zotero.Promise.delay(100);
    };
    await record('settings window renders and receives current values', settings.document.getElementById('model')?.value === 'fixture');
    await record('settings reflects local model destination', settings.document.getElementById('destination')?.textContent.includes('本机'));
    await record('resource preparation button exists', !!settings.document.getElementById('prepare'));
    await record('global settings no longer contains a page selector',!settings.document.getElementById('pages'));
    const waitPageDialog = async () => {
      for (let i=0;i<100;i++) {
        const dialog=controller.translationWindow;
        if (dialog?.document.readyState==='complete' && dialog.document.getElementById('pages')) return dialog;
        await Zotero.Promise.delay(50);
      }
      const dialog=controller.translationWindow;
      throw new Error('translation options did not open: '+JSON.stringify({closed:dialog?.closed,state:dialog?.document.readyState,url:dialog?.document.documentURI,root:dialog?.document.documentElement?.outerHTML.slice(0,500)}));
    };
    let pageChoice=controller.choosePages(win,'<b>Source paper</b>');
    let pageDialog=await waitPageDialog();
    await record('translation dialog shows source as plain text and starts with blank pages',pageDialog.document.getElementById('sourceTitle').textContent==='<b>Source paper</b>' && !pageDialog.document.getElementById('sourceTitle').querySelector('b') && pageDialog.document.getElementById('pages').value==='');
    pageDialog.document.getElementById('pages').value='8-3';
    pageDialog.document.getElementById('startTranslation').click();
    await record('invalid page range stays in the dialog with an error',!pageDialog.closed && pageDialog.document.getElementById('feedback').textContent.includes('结束页'));
    pageDialog.document.getElementById('pages').value=' 3-8,12 ';
    pageDialog.document.getElementById('startTranslation').click();
    await record('start translation returns this task page range',(await pageChoice)==='3-8,12');
    pageChoice=controller.choosePages(win,'Next paper');pageDialog=await waitPageDialog();
    await record('next paper starts with a fresh blank page selector',pageDialog.document.getElementById('pages').value==='');
    pageDialog.document.getElementById('startTranslation').click();
    await record('blank pages explicitly select the whole paper',(await pageChoice)==='');
    pageChoice=controller.choosePages(win,'Cancel paper');pageDialog=await waitPageDialog();
    pageDialog.document.getElementById('cancelTranslation').click();
    await record('cancel leaves no page choice',(await pageChoice)===null && !controller.translationWindow);
    let backend = settings.document.getElementById('backend');
    await record('backend chooser has two radios and no native select popup', settings.document.querySelectorAll('input[name="translationBackend"]').length === 2 && !settings.document.querySelector('select'));
    settings.document.getElementById('backendCodex').click();
    await record('clicking Codex radio updates the selected value', backend.value === 'codex' && settings.document.getElementById('backendCodex').checked && !settings.document.getElementById('backendApi').checked);
    await record('switching to Codex shows login settings and hides API fields', !settings.document.getElementById('codexSettings').hidden && settings.document.getElementById('apiSettings').hidden);
    await record('hidden API panel occupies no space and cannot cover the chooser', settings.document.getElementById('apiSettings').getBoundingClientRect().height === 0 && settings.document.getElementById('codexSettings').getBoundingClientRect().top >= settings.document.querySelector('.backend-options').getBoundingClientRect().bottom);
    await record('reasoning effort defaults to low', settings.document.getElementById('codexEffort').value === 'low');
    await record('Codex defaults to two concurrent batches and disables API request-rate field',settings.document.getElementById('codexConcurrency').value==='2' && settings.document.getElementById('qps').disabled && settings.document.getElementById('qpsHint').textContent.includes('同时翻译批次数'));
    settings.document.getElementById('codexConcurrency').value='3';
    await waitModels();
    const modelRadios = settings.document.querySelectorAll('input[name="codexModelChoice"]');
    await record('live Codex catalog becomes clickable radios without manual model input', modelRadios.length > 0 && modelRadios.length === controller.codexModels.length && settings.document.getElementById('codexModel').type === 'hidden');
    const chosen = controller.codexModels.find(model => model.efforts.includes('medium'));
    modelRadios[controller.codexModels.indexOf(chosen)].click();
    await record('model radio updates the selected model', settings.document.getElementById('codexModel').value === chosen.id);
    settings.document.querySelector('input[name="codexReasoningEffort"][value="medium"]').click();
    await record('clicking reasoning effort updates hidden setting', settings.document.getElementById('codexEffort').value === 'medium');
    settings.document.getElementById('settings').dispatchEvent(new settings.Event('submit', {bubbles:true,cancelable:true}));
    await Zotero.Promise.delay(200);
    await record('radio choice is saved through the actual form', controller.config().backend === 'codex');
    await record('saving settings drops the legacy page preference',!('pages' in JSON.parse(Services.prefs.getStringPref(controller.pref))));
    await record('model and effort are saved through the actual form', controller.config().codexEffort === 'medium' && controller.config().codexModel === chosen.id);
    await record('concurrent batch count is saved through the actual form',controller.config().codexConcurrency===3);
    settings.close();
    controller.openSettings(win);
    await Zotero.Promise.delay(700);
    settings = controller.settingsWindow; backend = settings.document.getElementById('backend');
    await waitModels();
    await record('reopening settings restores the Codex radio and visible panel', backend.value === 'codex' && settings.document.getElementById('backendCodex').checked && !settings.document.getElementById('codexSettings').hidden && settings.document.getElementById('apiSettings').hidden);
    await record('reopening restores model and selected reasoning effort', settings.document.getElementById('codexModel').value === chosen.id && settings.document.querySelector('input[name="codexReasoningEffort"][value="medium"]').checked);
    await record('reopening restores concurrent batch count',settings.document.getElementById('codexConcurrency').value==='3');
    const originalList = controller.listCodexModels;
    controller.listCodexModels = async () => [{id:'fixture-limited',name:'Capability fixture',description:'<b>literal description</b>',efforts:['low'],defaultEffort:'low',isDefault:true}];
    settings.document.getElementById('refreshModels').click(); await waitModels();
    await record('unavailable saved model requires a new choice', !settings.document.getElementById('codexModel').value && settings.document.getElementById('codexModelsStatus').textContent.includes('重新选择'));
    settings.document.querySelector('input[name="codexModelChoice"]').click();
    await record('model capabilities hide unsupported effort and reset selection', settings.document.getElementById('codexEffort').value === 'low' && settings.document.querySelector('input[value="medium"]').disabled && settings.document.querySelector('input[value="medium"]').parentElement.hidden);
    await record('catalog descriptions render as literal text', !settings.document.getElementById('codexModels').querySelector('b') && settings.document.getElementById('codexModels').textContent.includes('<b>literal description</b>'));
    controller.listCodexModels = async () => {throw new Error('fixture catalog unavailable');};
    settings.document.getElementById('refreshModels').click(); await waitModels();
    await record('failed refresh shows retry and removes stale model options', settings.document.getElementById('codexModelsStatus').dataset.error === 'true' && settings.document.querySelectorAll('input[name="codexModelChoice"]').length === 0);
    controller.listCodexModels = originalList;
    settings.document.getElementById('refreshModels').click(); await waitModels();
    settings.document.querySelector('input[name="codexModelChoice"]').click();
    await record('refresh retries the live catalog successfully', settings.document.querySelectorAll('input[name="codexModelChoice"]').length > 0 && settings.document.getElementById('codexModelsStatus').dataset.error === 'false');
    await controller.save({...config, backend:'codex',model:'',codexModel:chosen.id}, '');
    await record('Codex save preserves the original API key', controller.key(config.baseURL) === 'fixture-private-key');
    const codex = await controller.checkCodex({...config,codexBinary:'',codexModel:''});
    await record('native Codex ChatGPT login check succeeds without creating a chat', codex.account === 'chatgpt');
    await controller.save(config, 'fixture-private-key');
    settings.document.getElementById('backendApi').click();
    await record('clicking API radio switches back without overlapping panels', backend.value === 'api' && settings.document.getElementById('backendApi').checked && settings.document.getElementById('codexSettings').getBoundingClientRect().height === 0);
    await record('API settings remain available after switching back', !settings.document.getElementById('apiSettings').hidden);
    await record('API request-rate setting becomes editable again without losing its value',!settings.document.getElementById('qps').disabled && settings.document.getElementById('qps').value==='2');
    await controller.prepareResources();
    await record('native resource preparation succeeds without translation API', controller.status.includes('本地资源已就绪'));
    if (cfg.preview) {
      settings.document.getElementById('backendCodex').click(); await waitModels();
      settings.document.title = 'BabelDOC · 测试设置（独立文库）';
      settings.document.getElementById('codexBinary').scrollIntoView();
      await Zotero.Promise.delay(60000);
    }
    const paper = new Zotero.Item('journalArticle'); paper.setField('title', 'BabelDOC isolated test paper'); await paper.saveTx();
    const other = new Zotero.Item('journalArticle'); other.setField('title', 'Other selection'); await other.saveTx();
    const source = await Zotero.Attachments.importFromFile({file: cfg.fixture, parentItemID: paper.id});
    const originalBytes = await IOUtils.read(await source.getFilePathAsync());
    const originalGetter = babelScope.BabelHost.resource;
    const fixture = await originalGetter.call(babelScope.BabelHost, rootURI + 'fixture_worker.py');
    babelScope.BabelHost.resource = async function(url) {
      if (url === rootURI + 'content/worker.py') return fixture;
      return originalGetter.call(this, url);
    };
    const originalSelected = controller.selected;
    const originalChoosePages=controller.choosePages, originalRun=babelScope.BabelHost.run;
    let taskPages;
    controller.choosePages=async ()=>'1-5,8';
    babelScope.BabelHost.run=async function(options) {taskPages=options.request.pages;return originalRun.call(this,options);};
    const alerts = [], alertBusy = []; controller.alert = (_, message) => {alerts.push(message);alertBusy.push(controller.busy);};
    controller.selected = () => [source];
    const translation = controller.translate(win);
    controller.selected = () => [other];
    await translation;
    babelScope.BabelHost.run=originalRun;
    await record('per-task page range reaches the actual worker without being saved',taskPages==='1-5,8' && !('pages' in controller.config()));
    controller.choosePages=async ()=>'';
    await record('native translation workflow finishes', controller.status.includes('翻译完成'));
    const performancePath=PathUtils.join(Zotero.Profile.dir,'babeldoc-local','last-translation-performance.json');
    const performance=await IOUtils.readJSON(performancePath);
    await record('finished task shows elapsed time and model call count',controller.status.includes('0 分 12 秒') && controller.status.includes('模型调用 4 次'));
    await record('numeric performance report survives job cleanup without storing paper text or credentials',performance.performance.modelCalls===4 && performance.backend==='api' && !JSON.stringify(performance).includes('fixture-private-key') && !('input' in performance) && !('messages' in performance));
    const children = paper.getAttachments().map(id => Zotero.Items.get(id));
    await record('both generated PDFs attached to captured parent', children.length === 3 && other.getAttachments().length === 0);
    await record('translated and bilingual titles present', children.some(i => i.getField('title').startsWith('译文')) && children.some(i => i.getField('title').startsWith('双语对照')));
    await record('generated children have provenance tags', children.filter(i => i.getTags().some(t => t.tag === 'babeldoc:generated')).length === 2);
    const target = await babelScope.BabelCore.target([paper], controller.itemAPI());
    await record('repeat translation excludes generated PDFs', target.candidates.length === 1 && target.candidates[0].item.id === source.id);
    await record('source PDF unchanged', originalBytes.toString() === (await IOUtils.read(await source.getFilePathAsync())).toString());
    const jobRoot = PathUtils.join(Zotero.Profile.dir, 'babeldoc-local', 'jobs');
    await record('successful task removes working files', (await IOUtils.getChildren(jobRoot)).length === 0);
    controller.choosePages=async ()=>null;
    controller.selected=()=>[source];
    await controller.translate(win);
    await record('cancelling page selection starts no job and adds no attachments',!controller.busy && controller.status.includes('取消') && paper.getAttachments().length===3 && (await IOUtils.getChildren(jobRoot)).length===0);
    controller.choosePages=async ()=>'';
    if (Zotero.isWin) {
      const repro=await controller.directory();
      const name='论文_'+ 'long-paper-title-'.repeat(9)+'.mono.pdf';
      const longFile=PathUtils.join(repro,name),shortFile=PathUtils.join(repro,'translated.pdf');
      const {Subprocess}=ChromeUtils.importESModule('resource://gre/modules/Subprocess.sys.mjs');
      const writer=await Subprocess.call({command:cfg.python,arguments:['-c','import shutil,sys;shutil.copyfile(sys.argv[1],sys.argv[2])',cfg.fixture,longFile]});
      if ((await writer.wait()).exitCode!==0) throw new Error('Could not create long-path fixture');
      await record('Python creates a long-path PDF beyond 260 characters',longFile.length>260);
      const longPaper=new Zotero.Item('journalArticle');longPaper.setField('title','Windows long path reproduction');await longPaper.saveTx();
      let legacyError='';
      try {await Zotero.Attachments.importFromFile({file:longFile,parentItemID:longPaper.id,contentType:'application/pdf'});}
      catch(error){legacyError=String(error);}
      await record('legacy Zotero importer reproduces FILE_NOT_FOUND on an existing long path',legacyError.includes('NS_ERROR_FILE_NOT_FOUND'));
      const shortWriter=await Subprocess.call({command:cfg.python,arguments:['-c','import shutil,sys;shutil.copyfile(sys.argv[1],sys.argv[2])',longFile,shortFile]});
      if ((await shortWriter.wait()).exitCode!==0) throw new Error('Could not stage long-path fixture');
      const recovered=await Zotero.Attachments.importFromFile({file:shortFile,parentItemID:longPaper.id,contentType:'application/pdf'});
      await record('same bytes import successfully from a short staging path',!!recovered.id && (await IOUtils.read(await recovered.getFilePathAsync())).toString()===originalBytes.toString());
      const cleaner=await Subprocess.call({command:cfg.python,arguments:['-c','import pathlib,sys;pathlib.Path(sys.argv[1]).unlink()',longFile]});await cleaner.wait();
      await IOUtils.remove(repro,{recursive:true});
      const longSource=await Zotero.Attachments.importFromFile({file:cfg.fixture,parentItemID:longPaper.id});
      const previousChildren=longPaper.getAttachments().length;
      await controller.save({...config,model:'long-path-fixture'},'fixture-private-key');controller.selected=()=>[longSource];
      await controller.translate(win);
      const fixed=longPaper.getAttachments().map(id=>Zotero.Items.get(id)).filter(item=>item.getTags().some(t=>t.tag==='babeldoc:generated'));
      await record('actual translation controller imports both long-named output PDFs',longPaper.getAttachments().length===previousChildren+2 && fixed.length===2 && controller.status.includes('翻译完成'));
      await record('staged imports preserve bytes and use short filenames',fixed.every(item=>['translated.pdf','bilingual.pdf'].includes(item.attachmentFilename)) && (await IOUtils.read(await fixed[0].getFilePathAsync())).toString()===originalBytes.toString());
      await record('long-path success cleans all temporary originals and copies',(await IOUtils.getChildren(jobRoot)).length===0);
    }
    const partialPaper=new Zotero.Item('journalArticle'); partialPaper.setField('title','Partial translation fixture');await partialPaper.saveTx();
    const partialSource=await Zotero.Attachments.importFromFile({file:cfg.fixture,parentItemID:partialPaper.id});
    await controller.save({...config,model:'partial-fixture'},'fixture-private-key');
    controller.selected=()=>[partialSource]; const beforeAlerts=alerts.length;
    await controller.translate(win);
    const partialChildren=partialPaper.getAttachments().map(id=>Zotero.Items.get(id));
    await record('partial translation imports both PDFs instead of blocking the entire paper',partialChildren.length===3 && controller.status.includes('翻译已保存'));
    await record('partial attachments display untranslated label and review tags',partialChildren.filter(item=>item.getTags().some(t=>t.tag==='babeldoc:partial') && item.getField('title').includes('含未译原文')).length===2);
    await record('partial attachment notes identify pages and reasons',partialChildren.some(item=>item.getNote()?.includes('模型返回空译文') && item.getNote()?.includes('1（2 段）')));
    await record('partial result unlocks UI without failure modal',!controller.busy && alerts.length===beforeAlerts);
    await controller.save({...config, model: 'fail-secret'}, 'fixture-private-key');
    controller.selected = () => [source];
    await controller.translate(win);
    await record('worker failure redacts API key in UI', !controller.status.includes('fixture-private-key') && controller.status.includes('[REDACTED]'));
    await record('worker failure adds no attachments', paper.getAttachments().length === 3);
    await record('worker failure releases busy state before its error dialog',alertBusy.at(-1)===false);
    await controller.save({...config,model:'fail-after-output'},'fixture-private-key');controller.selected=()=>[source];
    await controller.translate(win);
    const retained=await IOUtils.getChildren(jobRoot);
    await record('engine failure preserves already generated PDFs for recovery',retained.length===1 && controller.status.includes('已生成的 PDF 保留在') && (await IOUtils.getChildren(retained[0])).some(path=>path.endsWith('.mono.pdf')));
    await IOUtils.remove(retained[0],{recursive:true});
    await controller.save({...config, model: 'wait-for-cancel'}, 'fixture-private-key');
    const cancelled = controller.translate(win);
    for (let i = 0; i < 100 && !babelScope.BabelHost.process; i++) await Zotero.Promise.delay(50);
    controller.cancel(); await cancelled;
    await record('cancellation kills worker and unlocks UI', !controller.busy && !babelScope.BabelHost.process && controller.status.includes('取消'));
    await record('cancellation adds no attachments and cleans files', paper.getAttachments().length === 3 && (await IOUtils.getChildren(jobRoot)).length === 0);
    await controller.save(config, '');
    await record('clearing API key removes password entry', controller.key(config.baseURL) === '');
    controller.selected = originalSelected;
    controller.choosePages=originalChoosePages;
    babelScope.BabelHost.resource = originalGetter;
    await IOUtils.writeJSON(cfg.report, {success: true, version: Zotero.version, checks});
  } catch (error) {
    await IOUtils.writeJSON(cfg.report, {success: false, error: String(error), stack: error.stack, checks});
  } finally {
    clearTimeout(timeout);
    await babelScope?.BabelDOC.shutdown();
    Services.startup.quit(Components.interfaces.nsIAppStartup.eForceQuit);
  }
}
